export type StarterPodTemplate = Array<{ podId: string; gridX: number; gridZ: number; rotation: number }>;

export function getStarterBaseForSite(siteId: string, crewSize: number = 4): StarterPodTemplate {
  const site = LANDING_SITE_MAP.get(siteId) || DEFAULT_LANDING_SITE;

  // Core shared 10 essential buildings around central core
  const baseCore: StarterPodTemplate = [
    { podId: 'living_pod', gridX: 0, gridZ: 0, rotation: 0 },
    { podId: 'oxygen_pod', gridX: 1, gridZ: 0, rotation: 0 },
    { podId: 'water_pod', gridX: 0, gridZ: 1, rotation: 0 },
    { podId: 'airlock_pod', gridX: -1, gridZ: 0, rotation: 0 },
    { podId: 'emergency_shelter_pod', gridX: 0, gridZ: -1, rotation: 0 },
    { podId: 'power_generation_pod', gridX: 2, gridZ: 0, rotation: 90 },
    { podId: 'medical_pod', gridX: -1, gridZ: 1, rotation: 0 },
    { podId: 'comm_pod', gridX: 1, gridZ: 1, rotation: 0 },
    { podId: 'waste_mgmt_pod', gridX: 0, gridZ: 2, rotation: 0 },
    { podId: 'storage_pod', gridX: -1, gridZ: -1, rotation: 0 },
    { podId: 'greenhouse_pod', gridX: 1, gridZ: -1, rotation: 0 },
    { podId: 'rover_garage_pod', gridX: -2, gridZ: 0, rotation: 0 },
  ];

  // Add site-specialized modules tailored to local environmental conditions
  if (site.starterProfile === 'solar_equatorial') {
    // High-sunlight dry plains: Dual Solar Power + Battery + Secondary Water Recovery (skip ground ice drill)
    baseCore.push(
      { podId: 'solar_power_pod', gridX: 2, gridZ: 1, rotation: 90 },
      { podId: 'solar_power_pod', gridX: 2, gridZ: -1, rotation: 90 },
      { podId: 'battery_storage_pod', gridX: 1, gridZ: 2, rotation: 0 },
      { podId: 'water_recovery_pod', gridX: -1, gridZ: 2, rotation: 0 }
    );
  } else if (site.starterProfile === 'polar_ice') {
    // Freezing polar latitudes with abundant buried ice: Water Extraction Drill + Nuclear Power + Temperature Control
    baseCore.push(
      { podId: 'water_extraction_pod', gridX: -2, gridZ: 1, rotation: 0 },
      { podId: 'nuclear_power_pod', gridX: 2, gridZ: -1, rotation: 90 },
      { podId: 'temp_control_pod', gridX: 1, gridZ: 2, rotation: 0 },
      { podId: 'battery_storage_pod', gridX: 2, gridZ: 1, rotation: 0 }
    );
  } else if (site.starterProfile === 'canyon_shadow') {
    // Deep canyon shade & dust hazards: Nuclear Power + Battery Bank + Weather Monitor (skip unreliable solar)
    baseCore.push(
      { podId: 'nuclear_power_pod', gridX: 2, gridZ: -1, rotation: 90 },
      { podId: 'battery_storage_pod', gridX: 2, gridZ: 1, rotation: 0 },
      { podId: 'water_extraction_pod', gridX: -2, gridZ: 1, rotation: 0 },
      { podId: 'weather_monitoring_pod', gridX: 1, gridZ: 2, rotation: 0 }
    );
  } else if (site.starterProfile === 'highland_dry') {
    // High-altitude dry volcanic plateaus: Water Recovery + Resource Processing + Hydroponics + Battery
    baseCore.push(
      { podId: 'water_recovery_pod', gridX: -2, gridZ: 1, rotation: 0 },
      { podId: 'resource_processing_pod', gridX: 2, gridZ: 1, rotation: 0 },
      { podId: 'hydroponics_pod', gridX: 1, gridZ: 2, rotation: 0 },
      { podId: 'battery_storage_pod', gridX: 2, gridZ: -1, rotation: 0 }
    );
  } else {
    // Balanced lakebed sites: Dual Solar + Battery + Water Extraction
    baseCore.push(
      { podId: 'solar_power_pod', gridX: 2, gridZ: 1, rotation: 90 },
      { podId: 'solar_power_pod', gridX: 2, gridZ: 2, rotation: 90 },
      { podId: 'battery_storage_pod', gridX: 2, gridZ: -1, rotation: 0 },
      { podId: 'water_extraction_pod', gridX: -2, gridZ: 1, rotation: 0 }
    );
  }

  if (
    site.starterProfile === 'canyon_shadow' &&
    (site.unsuitablePods.some((u) => u.podId === 'water_extraction_pod') || site.waterBonusL === 0)
  ) {
    const drillIdx = baseCore.findIndex((p) => p.podId === 'water_extraction_pod');
    if (drillIdx >= 0) {
      baseCore[drillIdx] = { ...baseCore[drillIdx], podId: 'water_recovery_pod' };
    }
  }

  // Scale starter capacity smoothly if mission crew exceeds 4 beds per Living Pod
  if (crewSize > 4) {
    baseCore.push({ podId: 'living_pod', gridX: -2, gridZ: -1, rotation: 0 });
  }
  if (crewSize >= 6 && !site.isImpossible) {
    baseCore.push({ podId: 'oxygen_pod', gridX: -1, gridZ: 2, rotation: 0 });
  }
  if (
    crewSize >= 5 &&
    !site.isImpossible &&
    (site.unsuitablePods.some((u) => u.podId === 'water_extraction_pod') || site.waterBonusL === 0)
  ) {
    baseCore.push({ podId: 'water_recovery_pod', gridX: 0, gridZ: -2, rotation: 0 });
  }

  return baseCore;
}

